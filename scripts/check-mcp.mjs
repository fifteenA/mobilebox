// Keyless check of the live MCP server, no dependencies (Node 24).
//   node scripts/check-mcp.mjs          # fail if prod, README tool table or server.json drifted
//   node scripts/check-mcp.mjs --write  # regenerate the README tool table from live tools/list
import { readFile, writeFile } from 'node:fs/promises'
import { isDeepStrictEqual } from 'node:util'

const base = process.env.MOBILESANDBOX_URL ?? 'https://mobilebox.dev'
const readmePath = new URL('../README.md', import.meta.url)
const serverJsonPath = new URL('../server.json', import.meta.url)
const errors = []

async function rpc(method, params) {
  const response = await fetch(`${base}/mcp`, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json', Accept: 'application/json, text/event-stream' },
    body: JSON.stringify({ jsonrpc: '2.0', id: 1, method, ...(params ? { params } : {}) }),
    signal: AbortSignal.timeout(30_000),
  })
  const text = await response.text()
  if (!response.ok) throw new Error(`${method} -> HTTP ${response.status} ${text}`)
  // Streamable HTTP may answer as JSON or as one SSE event.
  const json = text.startsWith('{') ? text : text.split('\n').find(line => line.startsWith('data:'))?.slice(5)
  const message = JSON.parse(json)
  if (message.error) throw new Error(`${method} -> ${JSON.stringify(message.error)}`)
  return message.result
}

const init = await rpc('initialize', {
  protocolVersion: '2025-06-18', capabilities: {}, clientInfo: { name: 'mobilebox-repo-ci', version: '1' },
})
if (init.serverInfo?.name !== 'mobilebox') errors.push(`initialize: unexpected serverInfo ${JSON.stringify(init.serverInfo)}`)
if (!init.capabilities?.tools) errors.push('initialize: server does not advertise tools')
console.log(`initialize ok: ${init.serverInfo?.name} ${init.serverInfo?.version}, protocol ${init.protocolVersion}`)

const { tools } = await rpc('tools/list')
if (!tools?.length) throw new Error('tools/list returned no tools')
console.log(`tools/list ok: ${tools.map(t => t.name).join(', ')}`)

const firstSentence = text => text.split(/(?<=\.)\s/)[0].replace(/\|/g, '\\|')
const args = schema => Object.keys(schema.properties ?? {})
  .map(name => (schema.required ?? []).includes(name) ? `\`${name}\`` : `\`${name}?\``).join(', ')
const table = [
  '| Tool | What it does | Arguments (`?` = optional) |',
  '|---|---|---|',
  ...tools.map(t => `| \`${t.name}\` | ${firstSentence(t.description ?? '')} | ${args(t.inputSchema) || '–'} |`),
].join('\n')

const START = '<!-- tools:start (generated by scripts/check-mcp.mjs --write) -->'
const END = '<!-- tools:end -->'
const readme = await readFile(readmePath, 'utf8')
const [before, rest] = readme.split(START)
if (rest === undefined || !rest.includes(END)) throw new Error('README.md is missing the tool table markers')
const current = rest.slice(0, rest.indexOf(END)).trim()
if (process.argv.includes('--write')) {
  await writeFile(readmePath, `${before}${START}\n${table}\n${END}${rest.slice(rest.indexOf(END) + END.length)}`)
  console.log('README.md tool table written')
} else if (current !== table) {
  errors.push('README.md tool table differs from live tools/list: run node scripts/check-mcp.mjs --write')
}

// server.json must equal the official MCP registry entry.
const local = JSON.parse(await readFile(serverJsonPath, 'utf8'))
const registry = await fetch(`https://registry.modelcontextprotocol.io/v0/servers?search=${encodeURIComponent(local.name)}`,
  { signal: AbortSignal.timeout(30_000) }).then(r => r.json())
const entry = registry.servers?.find(s => s.server.name === local.name && s._meta?.['io.modelcontextprotocol.registry/official']?.isLatest)
if (!entry) errors.push(`registry: no latest entry named ${local.name}`)
else if (!isDeepStrictEqual(entry.server, local)) errors.push('server.json differs from the official registry entry')
else console.log(`server.json ok: matches registry ${local.name} ${local.version}`)
if (!local.remotes?.some(r => r.url === `${base}/mcp`) && base === 'https://mobilebox.dev') {
  errors.push(`server.json remote is not ${base}/mcp`)
}

if (errors.length) {
  console.error(errors.map(e => `FAIL ${e}`).join('\n'))
  process.exit(1)
}
